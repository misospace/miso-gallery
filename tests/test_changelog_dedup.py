"""Regression test for issue #496.

The 0.2.1 release block in CHANGELOG.md was generated by release-please with
every fix appearing twice (once with a bare commit link and once with an
identical message plus `closes #NNN`). The duplication was caused by the
release-line reset (commit `d58131a`) leaving the same conventional commits
represented by two SHAs each; release-please emitted both. The duplication
was hand-edited out of CHANGELOG.md but release-please will not produce a
clean output for that historic release block again, so this test guards
against a future contributor re-adding the doubled lines (or accidentally
introducing duplicates in any future release block).
"""

from __future__ import annotations

import re
from collections import defaultdict
from pathlib import Path

CHANGELOG = Path(__file__).resolve().parents[1] / "CHANGELOG.md"

# Matches a release section header, e.g. `## [0.2.1](...compare/0.2.0...0.2.1) (2026-09-05)`.
_SECTION_HEADER = re.compile(r"^## \[(?P<version>[^\]]+)\]\(", re.MULTILINE)

# Matches a bullet entry shaped like `* **scope:** message ...` followed by
# either a commit link `([<sha>](...))` or a PR reference `([#NN](...))`.
_BULLET_LEAD = re.compile(r"^\* (?:\*\*(?P<scope>[^*]+):\*\* |)(?P<message>.+?)$")


def _release_block(text: str, version: str) -> str:
    """Return the text of the ``## [<version>]`` release block (inclusive)."""
    headers = list(_SECTION_HEADER.finditer(text))
    for index, header in enumerate(headers):
        if header.group("version") == version:
            start = header.start()
            end = headers[index + 1].start() if index + 1 < len(headers) else len(text)
            return text[start:end]
    raise AssertionError(f"CHANGELOG.md has no release block for version {version!r}")


def _bullets(block: str) -> list[tuple[str, str]]:
    """Yield (scope, message) for every well-formed bullet in ``block``.

    Scope is the text between `**` and `:**`, or empty string for unbolded bullets.
    Message is the rest of the bullet stripped of trailing/leading whitespace,
    with trailing SHA/PR link suffixes (``([<sha>](...))`` and ``closes [#N]``)
    collapsed to a single canonical form so that the same change documented with
    a bare commit link and the same change documented with a ``closes`` link
    produce the same key. This is the canonicalization that lets the dedup
    test catch the issue #496 doubling.
    """
    matches: list[tuple[str, str]] = []
    for line in block.splitlines():
        line = line.strip()
        if not line.startswith("* "):
            continue
        head = _BULLET_LEAD.match(line)
        if head is None:
            continue
        scope = (head.group("scope") or "").strip()
        message = head.group("message").strip()
        # Strip a trailing `, closes [#NN](...)` so `([<sha>](...))` and
        # `([<sha>](...)), closes [#NN](...)` collapse to the same key.
        message = re.sub(r",\s*closes \[#\d+\]\([^)]*\)\s*$", "", message)
        # Strip trailing bare SHA link like ` ([abc1234](...))` so the same
        # bullet with and without a SHA link collapse to the same key. This
        # is what issue #496 doubled in 0.2.1.
        message = re.sub(r" \(\[[0-9a-f]{7,}\]\([^)]*\)\)\s*$", "", message)
        # Older release-please emits bullets of the form
        # `* **scope:** message ([#NN](...)) ([abc1234](...))` where the PR
        # reference is also part of the message. Collapse those to the bare
        # `message` form too.
        message = re.sub(r" \(\[#\d+\]\([^)]*\)\)\s*$", "", message)
        matches.append((scope, message))
    return matches


def test_0_2_1_section_has_no_duplicate_entries():
    block = _release_block(CHANGELOG.read_text(encoding="utf-8"), "0.2.1")
    bullets = _bullets(block)

    grouped: dict[tuple[str, str], list[str]] = defaultdict(list)
    for scope, message in bullets:
        grouped[(scope, message)].append(f"* **{scope}:** {message}")

    duplicates = {key: lines for key, lines in grouped.items() if len(lines) > 1}
    assert not duplicates, (
        "CHANGELOG.md 0.2.1 release block contains duplicate entries "
        f"(same scope + message): {sorted(duplicates)}"
    )


def test_0_2_1_bug_fixes_list_expected_issue_closures():
    """The dedup kept the variant with the `closes #NNN` link for each fix."""
    block = _release_block(CHANGELOG.read_text(encoding="utf-8"), "0.2.1")

    expected = {
        "#444",
        "#445",
        "#446",
        "#448",
        "#450",
        "#452",
        "#453",
        "#454",
        "#455",
    }
    found: set[str] = set()
    for line in block.splitlines():
        for match in re.finditer(r"closes \[(#\d+)\]\(", line):
            found.add(match.group(1))

    missing = expected - found
    assert not missing, (
        f"CHANGELOG.md 0.2.1 release block is missing expected closes links: {sorted(missing)}"
    )



